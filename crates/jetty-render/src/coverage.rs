/// One bit per code point, U+0000–U+10FFFF (136 KiB): set when some installed
/// face maps it, or harfrust draws it without one (`HIDDEN`, `MAY_DECOMPOSE`).
pub(crate) struct Coverage(Box<[u64]>);

impl Coverage {
    /// Read the cmap of every face of `db` (~15 ms for 2000 faces whose files
    /// the font scan just read).
    pub(crate) fn build(db: &Database) -> Self {
        let mut bits = vec![0u64; 0x110000 / 64].into_boxed_slice();
        let mut set = |cp: u32| {
            if let Some(word) = bits.get_mut(cp as usize / 64) {
                *word |= 1 << (cp % 64);
            }
        };
        for &(lo, hi) in HIDDEN.iter().chain(MAY_DECOMPOSE) {
            (lo..=hi).for_each(&mut set);
        }
        for face in db.faces() {
            db.with_face_data(face.id, |data, index| {
                if let Ok(font) = FontRef::from_index(data, index) {
                    font.charmap().mappings().for_each(|(cp, _)| set(cp));
                }
            });
        }
        Self(bits)
    }

    /// Whether some installed font can draw `c`.
    pub(crate) fn covers(&self, c: char) -> bool {
        let cp = c as usize;
        self.0[cp / 64] & (1 << (cp % 64)) != 0
    }
}

static COVERAGE: OnceLock<Coverage> = OnceLock::new();

/// Build the process's [`Coverage`] from `db` on a background thread, once
/// (later calls do nothing): every layer's font system is a copy of the first
/// one's database, so one covers them all.
pub(crate) fn start(db: &Database) {
    static STARTED: Once = Once::new();
    STARTED.call_once(|| {
        let db = db.clone();
        // A failed spawn leaves no coverage: every char then gets the search.
        let _ = std::thread::Builder::new().name("jetty-font-coverage".into()).spawn(move || {
            let _ = COVERAGE.set(Coverage::build(&db));
        });
    });
}

/// The [`Coverage`], once built — `None` before (the first few ms after the
/// first font scan), when every char still gets the search.
pub(crate) fn get() -> Option<&'static Coverage> {
    COVERAGE.get()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hidden_and_decomposable_chars_count_as_drawable_without_a_font() {
        // No fonts at all: only what harfrust draws without a glyph of its own.
        let none = Coverage::build(&Database::new());
        for c in ['\u{FE0F}', '\u{200D}', '\u{E0041}', '\u{AD}', '\u{2F800}', '\u{AC00}', 'é', '\u{2ADC}'] {
            assert!(none.covers(c), "U+{:04X}", c as u32);
        }
        for c in ['a', '中', '\u{1CD00}', '\u{F0000}', '\u{10FFFF}', '\u{FFFD}', '\u{1F600}'] {
            assert!(!none.covers(c), "U+{:04X}", c as u32);
        }
        // The tables are sorted, disjoint ranges.
        for table in [HIDDEN, MAY_DECOMPOSE] {
            assert!(table.windows(2).all(|w| w[0].1 < w[1].0) && table.iter().all(|&(a, b)| a <= b));
        }
    }

    #[test]
    fn coverage_is_what_the_installed_fonts_map() {
        // Every char a font maps is covered; a char none maps is not (octant
        // art, Supplementary PUA-B — unless a font here has them).
        let fs = crate::TextLayer::build_font_system();
        let db = fs.db();
        let cov = Coverage::build(db);
        let mapped = |c: char| {
            db.faces().any(|f| {
                db.with_face_data(f.id, |data, index| {
                    FontRef::from_index(data, index).is_ok_and(|font| font.charmap().map(c).is_some())
                })
                .unwrap_or(false)
            })
        };
        for c in ['a', 'M', '中', '\u{23F5}', '\u{1CD00}', '\u{F0000}', '\u{10FFFD}', '\u{E0A0}'] {
            assert_eq!(cov.covers(c), mapped(c), "U+{:04X}", c as u32);
        }
    }
}
