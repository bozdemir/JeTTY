//! Which code points the installed fonts can draw at all.
//!
//! cosmic-text's font fallback, asked for a char that no installed face has,
//! tries every face in the database before it gives up — about 2000 here: ~7 ms
//! for each such char, ~240 ms for the first (every face is loaded, and kept).
//! Output full of them — octant art, emoji newer than the emoji font,
//! private-use icons, a `cat` of a binary — froze the window and the PTY drain
//! for seconds. [`get`] answers in one bit test whether a char is worth that
//! search; the renderer draws one no font has from the cell's own face (its
//! `.notdef` box, what the search ends with) without searching.

